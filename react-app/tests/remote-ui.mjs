import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { recordTestUser, interceptWhatsApp } from './remote-browser-helper.mjs'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) })
const base = process.env.APP_URL || 'http://127.0.0.1:5173'
const errors = []
try {
  const context = await browser.newContext({ viewport: { width:390,height:844 }, reducedMotion:'reduce' })
  let page = await context.newPage()
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/menu')
  await page.locator('[data-product="p1"]').click()
  await page.locator('#add-to-cart').click()
  await page.locator('#product-dialog').waitFor({state:'detached'})
  await recordTestUser(page)
  await page.locator('#open-cart').click()
  await page.locator('#customer-name').fill('Visitante de prueba')
  await page.locator('#order-notes').fill('Nota ficticia')
  await page.locator('#save-order').click()
  await page.getByText('Datos guardados.',{exact:true}).waitFor()
  assert.equal(await page.locator('#customer-name').getAttribute('maxlength'),'80')
  assert.equal(await page.locator('#order-notes').getAttribute('maxlength'),'500')
  await page.reload()
  await page.waitForFunction(()=>document.querySelector('#cart-count')?.textContent==='1')
  await page.locator('#open-cart').click()
  assert.equal(await page.locator('#customer-name').inputValue(),'Visitante de prueba')
  assert.equal(await page.locator('#order-notes').inputValue(),'Nota ficticia')
  await page.getByRole('button',{name:'Aumentar cantidad de Frozzi de mora'}).click()
  await page.waitForFunction(()=>document.querySelector('#cart-total')?.textContent==='Bs 22.00')
  await page.locator('#customer-name').fill('')
  await page.locator('#order-notes').fill('')
  await page.locator('#save-order').click()
  await page.getByText('Datos guardados.',{exact:true}).waitFor()
  await page.close()
  page = await context.newPage()
  await page.goto(base+'/menu')
  await page.waitForFunction(()=>document.querySelector('#cart-count')?.textContent==='2')
  await page.locator('#open-cart').click()
  assert.equal(await page.locator('#customer-name').inputValue(),'')
  assert.equal(await page.locator('#order-notes').inputValue(),'')
  // A separate browser context must not recover the first visitor's order.
  const otherContext = await browser.newContext()
  const other = await otherContext.newPage()
  await other.goto(base+'/menu')
  await other.locator('#open-cart').click()
  await other.getByText('Tu próximo antojo te espera',{exact:true}).waitFor()
  await recordTestUser(other)
  assert.equal(await other.locator('.cart-item').count(),0)
  await otherContext.close()
  // Simulate transport failure only; no fake database success or fake persistence.
  await page.route('**/rest/v1/rpc/change_cart',route=>route.abort('internetdisconnected'))
  await page.getByRole('button',{name:'Aumentar cantidad de Frozzi de mora'}).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.locator('#cart-total').innerText(),'Bs 22.00')
  assert.equal(await page.locator('#checkout').isDisabled(),true)
  await page.unroute('**/rest/v1/rpc/change_cart')
  await page.getByRole('button',{name:'Actualizar pedido',exact:true}).click()
  await page.getByRole('alert').waitFor({state:'detached'})
  await interceptWhatsApp(page)
  await page.locator('#checkout').click()
  await page.waitForFunction(()=>window.orderUrl?.startsWith('https://wa.me/'))
  assert.ok(new URL(await page.evaluate(()=>window.orderUrl)).searchParams.get('text').includes('Bs 22.00'))
  assert.equal(await page.locator('.history-order').count(),0)
  await page.getByText('Tu próximo antojo te espera',{exact:true}).waitFor()
  await page.reload()
  await page.locator('#open-cart').click()
  await page.getByText('Tu próximo antojo te espera',{exact:true}).waitFor()
  assert.equal(await page.locator('.cart-item').count(),0)
  await context.close()
  assert.deepEqual(errors,[])
  console.log('PASS: browser CRUD, reload/new page persistence, cleared metadata, separate visitor, transport failure/retry, WhatsApp and empty state.')
} finally { await browser.close() }
